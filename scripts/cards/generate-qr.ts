/*
 * Writes content/generated/qr.ts from content/cards.ts.
 * Dev-only: the `qrcode` package is a devDependency and never ships to the browser.
 * Run: npm run cards:qr (scripts/cards/qr-cli.ts); cards:print runs it first.
 */
import { resolve } from "node:path";
import * as prettier from "prettier";
import { cards, cardUrl } from "../../content/cards";
import { makeQr } from "./qr";

export const OUT = resolve(process.cwd(), "content/generated/qr.ts");

export async function renderQrModule(): Promise<string> {
  const entries = cards.map((card) => {
    const url = cardUrl(card);
    const qr = makeQr(url);
    return `  ${JSON.stringify(card.slug)}: { url: ${JSON.stringify(url)}, size: ${qr.size}, path: ${JSON.stringify(qr.path)} },`;
  });
  const source = `/*
 * GENERATED by scripts/cards/generate-qr.ts from content/cards.ts. Do not edit.
 * Regenerate with: npm run cards:qr
 * Each path draws the dark modules of a QR code (error correction Q) inside a
 * square viewBox of \`size\` modules that already includes the 4-module quiet zone.
 */
export type GeneratedQr = { url: string; size: number; path: string };

export const qrCodes: Record<string, GeneratedQr> = {
${entries.join("\n")}
};
`;
  const config = (await prettier.resolveConfig(OUT)) ?? {};
  return prettier.format(source, { ...config, filepath: OUT });
}
