/**
 * `npm run seo:check`: inspect the prerendered output of `next build` (no browser).
 * Run after `npm run build`. Exits 1 with a table of problems.
 *
 * Env: SEO_CHECK_ORIGIN (default https://sidedataa.com), BLOG_FIXTURES=1 (allow fixture posts).
 */
import fs from "node:fs";
import path from "node:path";
import { formatIssues, runChecks } from "./lib";

const root = process.cwd();
const appDir = path.join(root, ".next", "server", "app");
const origin = (process.env.SEO_CHECK_ORIGIN || "https://sidedataa.com").replace(
  /\/+$/,
  "",
);

if (!fs.existsSync(appDir)) {
  console.error("seo:check: .next/server/app not found. Run `npm run build` first.");
  process.exit(2);
}

function walk(dir: string): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? walk(full) : [full];
  });
}

const pages: Record<string, string> = {};
const otherRoutes = new Set<string>(["/"]);
for (const file of walk(appDir)) {
  const rel = path.relative(appDir, file).split(path.sep).join("/");
  if (rel.endsWith(".html")) {
    if (rel.startsWith("_")) continue; // _not-found, _global-error
    const p = rel === "index.html" ? "/" : `/${rel.slice(0, -".html".length)}`;
    pages[p] = fs.readFileSync(file, "utf8");
  } else if (rel.endsWith(".body")) {
    otherRoutes.add(`/${rel.slice(0, -".body".length)}`);
  }
}

// Dynamic (non-prerendered) routes without parameters, e.g. /form-status, /healthz.
const manifestFile = path.join(root, ".next", "server", "app-path-routes-manifest.json");
if (fs.existsSync(manifestFile)) {
  const manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8")) as Record<
    string,
    string
  >;
  for (const route of Object.values(manifest)) {
    if (!route.includes("[") && !route.startsWith("/_")) otherRoutes.add(route);
  }
}
// Static files in public/.
const publicDir = path.join(root, "public");
if (fs.existsSync(publicDir)) {
  for (const f of walk(publicDir)) {
    otherRoutes.add(`/${path.relative(publicDir, f).split(path.sep).join("/")}`);
  }
}
// Metadata routes served without a .body file under their final name.
for (const f of ["sitemap.xml", "robots.txt", "feed.xml"]) {
  if (fs.existsSync(path.join(appDir, f))) otherRoutes.add(`/${f}`);
}

const read = (f: string) => {
  const p = path.join(appDir, f);
  return fs.existsSync(p) ? fs.readFileSync(p, "utf8") : undefined;
};
const sitemapXml = read("sitemap.xml.body");
const robotsTxt = read("robots.txt.body");
const feedXml = read("feed.xml.body");
if (sitemapXml === undefined || robotsTxt === undefined) {
  console.error("seo:check: sitemap.xml or robots.txt was not generated by the build.");
  process.exit(1);
}

const { issues, pageCount } = runChecks({
  origin,
  pages,
  otherRoutes,
  sitemapXml,
  robotsTxt,
  feedXml,
  allowFixtures: process.env.BLOG_FIXTURES === "1",
});

if (issues.length) {
  console.error(
    `seo:check FAILED: ${issues.length} problem(s) across ${pageCount} pages\n`,
  );
  console.error(formatIssues(issues));
  process.exit(1);
}
console.log(
  `seo:check OK: ${pageCount} prerendered pages, sitemap, robots.txt and feed passed.`,
);
